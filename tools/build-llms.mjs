// Builds llms-full.txt (node tools/build-llms.mjs): README + AGENTS.md + the TypeScript declarations in one plain-text file,
// so an AI agent can read the whole API at once.
import { readFileSync, writeFileSync } from 'node:fs';

const part = (title, file) => `\n\n==================== ${title} (${file}) ====================\n\n${readFileSync(file, 'utf8').trim()}\n`;
const out = '# open-dom-heatmap — full reference for AI agents (generated by tools/build-llms.mjs)\n' +
  part('README', 'README.md') + part('Agent instructions', 'AGENTS.md') + part('API declarations', 'src/index.d.ts');
writeFileSync('llms-full.txt', out);
console.log(`llms-full.txt: ${out.length} characters`);
